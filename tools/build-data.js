/*
  Combines the content files into one file per level, so phones download a few files instead of ~150.

    node tools/build-data.js           build data/build/*.js
    node tools/build-data.js --check   only check that data/build is up to date (exit code 1 if not)

  Run it after every change in data/ (and always before publishing).
  The files you edit stay the same: data/levels.js and data/<level>/..., data/kasblar/...
  Output (do not edit by hand, it is overwritten):
    data/build/levels.js   = data/levels.js + the list of bundles (RUSCHA_BUNDLES)
    data/build/shared.js   = every file of RUSCHA_SHARED (Kasblar)
    data/build/a1.js, a2.js, …  = every file of that level, in the order of data/levels.js
*/
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const crypto = require("crypto");

const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "data", "build");
const CHECK = process.argv.includes("--check");
const rel = p => path.join(ROOT, ...p.split("/"));

/* Read the level list exactly as the browser does. */
const levelsSrc = fs.readFileSync(rel("data/levels.js"), "utf8");
const box = {};
vm.runInNewContext(levelsSrc + "\nthis.L = RUSCHA_LEVELS; this.S = RUSCHA_SHARED;", box, { filename: "data/levels.js" });
const levels = box.L, shared = box.S || [];

const errors = [];
const bundles = [{ id: "shared", level: "", files: shared }]
  .concat(levels.filter(l => l.files && l.files.length).map(l => ({ id: l.id, level: l.id, files: l.files })));

const seenFile = {};
const outputs = {}; // file name → text
bundles.forEach(b => {
  const parts = b.files.map(f => {
    if (seenFile[f]) errors.push(f + " is listed twice (" + seenFile[f] + " and " + b.id + ")");
    seenFile[f] = b.id;
    let src;
    try { src = fs.readFileSync(rel(f), "utf8").replace(/^﻿/, ""); } catch (e) { errors.push("missing file: " + f); return ""; }
    const body = "function () {\n" + src.replace(/\s+$/, "") + "\n}";
    try { new vm.Script("(" + body + ")", { filename: f }); } catch (e) { errors.push(f + ": " + e.message); }
    return "[" + JSON.stringify(f) + ", " + body + "]";
  });
  outputs[b.id + ".js"] =
    "/* Generated by tools/build-data.js from data/levels.js — do not edit. Edit the files listed below and run: node tools/build-data.js */\n" +
    "Ruscha.bundle(" + JSON.stringify(b.id) + ", [\n" + parts.join(",\n\n") + "\n]);\n";
});

/* Run every bundle once with a stand-in Ruscha: catches runtime errors and Russian text used twice in different levels. */
const firstRu = {};
const dups = [];
bundles.forEach(b => {
  const calls = { n: 0 };
  const note = (kind, ru, where) => {
    const k = kind + ":" + String(ru || "").toLowerCase().replace(/ё/g, "е").replace(/[^a-zа-я0-9]+/g, " ").trim();
    if (firstRu[k] && firstRu[k] !== b.id) dups.push(b.id + " repeats " + firstRu[k] + ": " + ru + " (" + where + ")");
    else firstRu[k] = firstRu[k] || b.id;
  };
  const any = () => { calls.n++; };
  const Ruscha = {
    bundle(id, parts) {
      parts.forEach(([f, fn]) => {
        try { fn(); } catch (e) { errors.push(f + " (when run): " + e.message); }
      });
    },
    addTopic(t) { calls.n++; (t.phrases || []).forEach(p => note("p", p.ru, t.id)); },
    addJob: any,
    addJobTab(id, key, part) { calls.n++; ((part && part.phrases) || []).forEach(p => note("p", p.ru, id + " " + key)); },
    addWords(l) { calls.n++; (l.groups || []).forEach(g => g.words.forEach(w => note("w", w[0], l.id))); },
    addListening: any, addLive: any, addShortcuts: any, addSpeaking: any, addTest: any
  };
  vm.runInNewContext(outputs[b.id + ".js"], { Ruscha }, { filename: "data/build/" + b.id + ".js" });
  if (!calls.n && b.files.length) errors.push("data/build/" + b.id + ".js adds nothing");
});

/* The list the app and sw.js read: name, level, size in bytes (for the progress bar) and a short hash (new hash = new URL). */
const list = bundles.map(b => {
  const text = outputs[b.id + ".js"];
  return {
    id: b.id, level: b.level, file: "data/build/" + b.id + ".js",
    bytes: Buffer.byteLength(text, "utf8"),
    v: crypto.createHash("sha1").update(text).digest("hex").slice(0, 10)
  };
});
outputs["levels.js"] = levelsSrc.replace(/\s+$/, "") + "\n\n" +
  "/* ---- Added by tools/build-data.js (do not edit here: edit data/levels.js and run the script) ---- */\n" +
  "var RUSCHA_BUNDLES = " + JSON.stringify(list, null, 1).replace(/\n\s*/g, " ") + ";\n";

if (errors.length) {
  console.error("❌ Not built. Fix these first:\n  " + errors.join("\n  "));
  process.exit(1);
}
if (dups.length) console.warn("⚠️  The same Russian text appears in two levels (the first level wins):\n  " + dups.join("\n  "));

/* Write (or only compare in --check mode). */
let changed = [];
if (!CHECK) fs.mkdirSync(OUT, { recursive: true });
Object.keys(outputs).forEach(name => {
  const p = path.join(OUT, name);
  const old = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
  if (old === outputs[name]) return;
  changed.push(name);
  if (!CHECK) fs.writeFileSync(p, outputs[name]);
});
const extra = fs.existsSync(OUT) ? fs.readdirSync(OUT).filter(n => !(n in outputs)) : [];
extra.forEach(n => { changed.push(n + " (old, removed)"); if (!CHECK) fs.unlinkSync(path.join(OUT, n)); });

if (CHECK) {
  if (changed.length) { console.error("❌ data/build is out of date (" + changed.join(", ") + "). Run: node tools/build-data.js"); process.exit(1); }
  console.log("✅ data/build is up to date.");
} else {
  list.forEach(b => console.log("  " + b.file.padEnd(22) + String(Math.round(b.bytes / 1024)).padStart(5) + " KB  " +
    bundles.find(x => x.id === b.id).files.length + " files"));
  console.log(changed.length ? "✅ Built: " + changed.join(", ") : "✅ Nothing changed.");
}
